const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const model = {};
vm.createContext(model);
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'Model.js'), 'utf8'), model);
assert.equal(model.revealOffset(50, 100, 25, 40, 400), 25);
assert.equal(model.revealOffset(50, 100, 180, 40, 400), 120);
assert.equal(model.revealOffset(50, 100, 75, 40, 400), 50);
assert.equal(model.clampOffset(999, 300, 100), 200);
assert.equal(model.clampOffset(-1, 300, 100), 0);
assert.equal(model.clampOffset(99, 50, 100), 0);
assert.equal(model.wheelStep(0, 0, 0, 120, false, true, 48), -48);
assert.equal(model.wheelStep(0, 0, 0, 120, true, true, 48), 48);
assert.equal(model.wheelStep(-5, 0, 0, 0, true, false, 48), 5);
assert.equal(model.wheelStep(0, -5, 0, 0, true, false, 48), 5);
assert.equal(model.wheelStep(0, 0, -120, 0, true, true, 48), 48);
console.log('11 model checks passed');
